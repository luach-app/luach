"""Alembic's entry point: run luach's migrations against one database.

The models (luach.db) are the schema's description, so a revision can be
autogenerated from them (`hatch run revision "what changes"`) -- against a
database that tulip's memory shares: only luach's own tables are compared,
so autogenerate never proposes dropping tulip's.
"""

from __future__ import annotations

from typing import Any

from alembic import context
from sqlalchemy import create_engine, pool

from luach.db import Base

target_metadata = Base.metadata
OURS = set(target_metadata.tables)


def include_name(name: str | None, type_: str, _parents: Any) -> bool:
    return type_ != "table" or name in OURS


url = context.config.get_main_option("sqlalchemy.url") or ""
engine = create_engine(url, poolclass=pool.NullPool)
with engine.connect() as connection:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        include_name=include_name,
        transaction_per_migration=True,
        compare_type=True,
    )
    with context.begin_transaction():
        context.run_migrations()
engine.dispose()
