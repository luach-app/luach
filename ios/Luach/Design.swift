import SwiftUI

// The few pieces every screen shares, so a person, a greeting and a quiet day look the same
// wherever they appear.

/// A person as a round badge: their initial on their colour (the family's colours, as on the
/// web board), or a household symbol for the family as a whole.
struct PersonAvatar: View {
    let name: String
    let hex: String
    var size: CGFloat = 30

    var body: some View {
        let colour = Color(luachHex: hex)
        ZStack {
            Circle().fill(colour ?? Color.secondary.opacity(0.25))
            if hex.isEmpty {
                Image(systemName: "house.fill")
                    .font(.system(size: size * 0.45, weight: .semibold))
                    .foregroundStyle(.secondary)
            } else {
                Text(initial)
                    .font(.system(size: size * 0.48, weight: .bold, design: .rounded))
                    .foregroundStyle(colour == nil ? Color.primary : Color.ink(on: hex))
            }
        }
        .frame(width: size, height: size)
        .accessibilityHidden(true)
    }

    private var initial: String {
        name.trimmingCharacters(in: .whitespaces).first.map { String($0).uppercased() } ?? "·"
    }
}

/// "Good afternoon, Robin", the way a person would open the day.
enum Greeting {
    static func text(_ name: String, at date: Date = .now) -> String {
        let hour = Calendar.current.component(.hour, from: date)
        let first = name.split(separator: " ").first.map(String.init) ?? name
        switch hour {
        case 5..<12: return String(localized: "Good morning, \(first)")
        case 12..<18: return String(localized: "Good afternoon, \(first)")
        default: return String(localized: "Good evening, \(first)")
        }
    }
}

/// A day with nothing on it, said kindly, with a way to add something when there is one.
struct QuietDay: View {
    let title: LocalizedStringKey
    var message: LocalizedStringKey?
    var symbol = "sun.max.fill"
    var action: (label: LocalizedStringKey, run: () -> Void)?

    var body: some View {
        VStack(spacing: 10) {
            Image(systemName: symbol)
                .font(.system(size: 34, weight: .medium))
                .foregroundStyle(.tint)
                .symbolRenderingMode(.hierarchical)
                .padding(.top, 6)
            Text(title).font(.headline)
            if let message {
                Text(message).font(.subheadline).foregroundStyle(.secondary).multilineTextAlignment(.center)
            }
            if let action {
                Button(action: action.run) {
                    Label(action.label, systemImage: "plus")
                        .font(.subheadline.weight(.semibold))
                }
                .buttonStyle(.bordered)
                .buttonBorderShape(.capsule)
                .padding(.top, 2)
            }
        }
        .frame(maxWidth: .infinity)
        .padding(.vertical, 14)
    }
}

// MARK: On the accent

// `Color.accentOn` (the asset catalog's AccentOn, symbol generated by Xcode) is the ink for
// anything drawn on the amber accent: send, the mic, a chosen chip, the Board's +. A near-black,
// as the web's `--accent-on`: white on amber is about 2.5:1 in light and 1.8:1 in dark; this is
// over 7:1 in both, and black under Increase Contrast.

extension View {
    /// A filled accent button (`.borderedProminent`) whose words are dark enough to read.
    func prominentAccent() -> some View {
        buttonStyle(.borderedProminent).foregroundStyle(Color.accentOn)
    }
}

// MARK: Unsaved edits

/// Asks "Discard changes?" before a form with unsaved edits goes: its Back button (a screen
/// pushed in Settings) or Cancel (a sheet) asks first, and a swipe cannot drop them silently.
struct DiscardGuard: ViewModifier {
    let dirty: Bool
    /// The form is a sheet with its own Cancel: that button calls `ask` instead of dismissing.
    @Binding var asking: Bool
    var pushed: Bool
    @Environment(\.dismiss) private var dismiss

    func body(content: Content) -> some View {
        content
            .navigationBarBackButtonHidden(pushed && dirty)
            .interactiveDismissDisabled(dirty)
            .toolbar {
                if pushed && dirty {
                    ToolbarItem(placement: .topBarLeading) {
                        Button { asking = true } label: {
                            HStack(spacing: 4) {
                                Image(systemName: "chevron.backward").fontWeight(.semibold)
                                Text("Back")
                            }
                        }
                        .accessibilityLabel(Text("Back"))
                        .accessibilityIdentifier("discard.back")
                    }
                }
            }
            .confirmationDialog("Discard changes?", isPresented: $asking, titleVisibility: .visible) {
                Button("Discard changes", role: .destructive) { dismiss() }
                Button("Keep editing", role: .cancel) {}
            } message: {
                Text("What you changed here has not been saved.")
            }
    }
}

extension View {
    /// A screen pushed in a navigation stack: while `dirty`, Back asks before the edits go.
    func confirmsDiscard(_ dirty: Bool) -> some View {
        modifier(DiscardAsker(dirty: dirty))
    }

    /// A sheet whose Cancel sets `asking` when `dirty` (and dismisses otherwise).
    func confirmsDiscard(_ dirty: Bool, asking: Binding<Bool>) -> some View {
        modifier(DiscardGuard(dirty: dirty, asking: asking, pushed: false))
    }
}

/// `confirmsDiscard(_:)` for a pushed screen, holding its own question.
private struct DiscardAsker: ViewModifier {
    let dirty: Bool
    @State private var asking = false

    func body(content: Content) -> some View {
        content.modifier(DiscardGuard(dirty: dirty, asking: $asking, pushed: true))
    }
}
